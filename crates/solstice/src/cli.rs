//! The command line.
//!
//! `docs/testing.md` §2.1 makes a design demand of this module: pairing must be
//! scriptable, because the headless Moonlight client takes its PIN as an
//! argument (`moonlight pair -pin 1234`). So pairing is
//! `solstice pair --pin 1234`, not a web form -- and there is no web UI at all,
//! which also removes the place Sunshine's worst CVEs lived.
//!
//! Everything but `run` talks to the running daemon over its management socket
//! (`crate::management`).

use std::path::PathBuf;

use clap::{Parser, Subcommand};

use crate::endpoint::Spec;

/// A proxy that lets a Moonlight client connect to a VNC or SPICE desktop.
#[derive(Parser, Debug)]
#[command(name = "solstice", version, about)]
pub struct Cli {
    /// Configuration file.
    #[arg(short, long, default_value = "/etc/solstice/solstice.toml")]
    pub config: PathBuf,

    /// Log filter, e.g. `info`, `solstice=debug`.
    #[arg(long, env = "SOLSTICE_LOG", default_value = "info")]
    pub log: String,

    /// What to do.
    #[command(subcommand)]
    pub command: Command,
}

/// Subcommands.
#[derive(Subcommand, Debug)]
pub enum Command {
    /// Run the daemon.
    Run {
        /// A remote desktop to offer, as `name=...,kind=...[,key=value...]`,
        /// in addition to the configuration's `[[endpoint]]` tables. Repeat
        /// for several; none at all is fine.
        ///
        /// The keys are the `[[endpoint]]` keys: name, kind (vnc, spice,
        /// testpattern), host, port, security, password_file, ca_file and
        /// audio. Not password, which every user on the machine could read
        /// here.
        #[arg(long = "endpoint", value_name = "SPEC", value_parser = Spec::parse)]
        endpoints: Vec<Spec>,
    },

    /// Open a time-boxed pairing window on the running daemon, and wait for it.
    ///
    /// The PIN is generated by the *client* and read out to the user; Moonlight
    /// hard-codes four digits, so the window and the attempt limit are the real
    /// control rather than the PIN's entropy (`docs/security.md` §1.1).
    ///
    /// Exits 0 once a client has paired, and non-zero if the window runs out,
    /// pairing locks out, or another `solstice pair` replaces it. Interrupting
    /// it closes the window.
    Pair {
        /// The PIN the client is displaying.
        #[arg(long)]
        pin: String,
        /// How long to leave the window open, at most 10m. Defaults to
        /// `security.pairing_window` in the daemon's configuration.
        #[arg(long)]
        window: Option<humantime::Duration>,
    },

    /// Show what the running daemon is doing.
    Status,

    /// List paired clients.
    ///
    /// Asks the running daemon; reads the state directory directly if none is
    /// running.
    ListClients,

    /// Revoke a paired client, effective immediately.
    ///
    /// Asks the running daemon; edits the state directory directly if none is
    /// running.
    Revoke {
        /// At least four leading hex digits of the fingerprint `list-clients`
        /// prints.
        prefix: String,
    },

    /// Add, remove or list the running daemon's endpoints.
    ///
    /// A change lasts until the daemon stops. A restart is back to the
    /// configuration's `[[endpoint]]` tables and `run`'s `--endpoint` flags.
    Endpoint {
        /// What to do.
        #[command(subcommand)]
        action: EndpointAction,
    },
}

/// `solstice endpoint ...`.
#[derive(Subcommand, Debug)]
pub enum EndpointAction {
    /// Offer one more endpoint, at once.
    ///
    /// The SPEC is what `run --endpoint` takes. The daemon reads
    /// password_file and ca_file itself, so they must be absolute paths.
    Add {
        /// `name=...,kind=...[,key=value...]`.
        #[arg(value_name = "SPEC", value_parser = checked_spec)]
        spec: String,
    },
    /// Stop offering an endpoint. A stream from it is ended, and the client
    /// told.
    Remove {
        /// Its name, exactly as `list` prints it.
        name: String,
    },
    /// Every endpoint on offer.
    List,
}

/// Refuse here what the daemon would refuse anyway, before connecting.
fn checked_spec(spec: &str) -> Result<String, String> {
    Spec::parse(spec)?.require_absolute_paths()?;
    Ok(spec.to_owned())
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::CommandFactory;

    #[test]
    fn the_cli_is_well_formed() {
        Cli::command().debug_assert();
    }

    #[test]
    fn pairing_takes_a_pin_on_the_command_line() {
        let cli = Cli::parse_from(["solstice", "pair", "--pin", "1234"]);
        let Command::Pair { pin, window } = cli.command else {
            panic!("expected pair")
        };
        assert_eq!(pin, "1234");
        assert!(window.is_none(), "the daemon's configured window applies");

        let cli = Cli::parse_from(["solstice", "pair", "--pin", "1234", "--window", "2m"]);
        let Command::Pair { window, .. } = cli.command else {
            panic!("expected pair")
        };
        assert_eq!(window.map(|w| w.as_secs()), Some(120));
    }

    #[test]
    fn run_is_a_subcommand_not_a_default() {
        let Command::Run { endpoints } = Cli::parse_from(["solstice", "run"]).command else {
            panic!("expected run")
        };
        assert!(endpoints.is_empty(), "no endpoints is a valid start");
    }

    #[test]
    fn endpoint_subcommands_check_the_spec_before_connecting() {
        let cli = Cli::parse_from([
            "solstice",
            "endpoint",
            "add",
            "name=Build box,kind=vnc,host=10.0.0.5",
        ]);
        let Command::Endpoint {
            action: EndpointAction::Add { spec },
        } = cli.command
        else {
            panic!("expected endpoint add")
        };
        assert_eq!(spec, "name=Build box,kind=vnc,host=10.0.0.5");

        for spec in [
            "name=A,kind=vnc,password=x",
            "name=A,kind=vnc,password_file=pw",
            "kind=vnc",
        ] {
            assert!(
                Cli::try_parse_from(["solstice", "endpoint", "add", spec]).is_err(),
                "{spec} was accepted"
            );
        }
        assert!(matches!(
            Cli::parse_from(["solstice", "endpoint", "remove", "Build box"]).command,
            Command::Endpoint {
                action: EndpointAction::Remove { .. }
            }
        ));
    }

    #[test]
    fn endpoints_are_repeatable_and_parsed_up_front() {
        let cli = Cli::parse_from([
            "solstice",
            "run",
            "--endpoint",
            "name=My Spice X,kind=spice,host=127.0.0.1,port=7878",
            "--endpoint",
            "name=Bars,kind=testpattern",
        ]);
        let Command::Run { endpoints } = cli.command else {
            panic!("expected run")
        };
        assert_eq!(
            endpoints
                .iter()
                .map(|e| e.name.as_str())
                .collect::<Vec<_>>(),
            ["My Spice X", "Bars"]
        );
        assert_eq!(endpoints[0].port, Some(7878));

        let err = Cli::try_parse_from([
            "solstice",
            "run",
            "--endpoint",
            "name=A,kind=vnc,password=x",
        ])
        .unwrap_err()
        .to_string();
        assert!(err.contains("password_file"), "{err}");
    }
}
