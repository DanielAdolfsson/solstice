//! The command line.
//!
//! `docs/testing.md` §2.1 makes a design demand of this module: pairing must be
//! scriptable, because the headless Moonlight client takes its PIN as an
//! argument (`moonlight pair -pin 1234`). So pairing is
//! `solstice pair --pin 1234`, not a web form -- and there is no web UI at all,
//! which also removes the place Sunshine's worst CVEs lived.

use std::path::PathBuf;

use clap::{Parser, Subcommand};

/// A proxy that lets a Moonlight client connect to a VNC or SPICE desktop.
#[derive(Parser, Debug)]
#[command(name = "solstice", version, about)]
pub struct Cli {
    /// Configuration file.
    #[arg(short, long, default_value = "/etc/solstice/solstice.toml")]
    pub config: PathBuf,

    /// Log filter, e.g. `info`, `solstice=debug`.
    #[arg(long, env = "SOLSTICE_LOG", default_value = "info")]
    pub log: String,

    /// What to do.
    #[command(subcommand)]
    pub command: Command,
}

/// Subcommands.
#[derive(Subcommand, Debug)]
pub enum Command {
    /// Run the daemon.
    Run,

    /// Open a time-boxed pairing window.
    ///
    /// The PIN is generated by the *client* and read out to the user; Moonlight
    /// hard-codes four digits, so the window and the attempt limit are the real
    /// control rather than the PIN's entropy (`docs/security.md` §1.1).
    Pair {
        /// The PIN the client is displaying.
        #[arg(long)]
        pin: String,
        /// How long to leave the window open.
        #[arg(long, default_value = "60s")]
        window: humantime::Duration,
    },

    /// List paired clients.
    ListClients,

    /// Revoke a paired client by the prefix of its certificate fingerprint.
    Revoke {
        /// Certificate DER prefix, as printed by `list-clients`.
        prefix: String,
    },
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::CommandFactory;

    #[test]
    fn the_cli_is_well_formed() {
        Cli::command().debug_assert();
    }

    #[test]
    fn pairing_takes_a_pin_on_the_command_line() {
        let cli = Cli::parse_from(["solstice", "pair", "--pin", "1234"]);
        let Command::Pair { pin, window } = cli.command else {
            panic!("expected pair")
        };
        assert_eq!(pin, "1234");
        assert_eq!(window.as_secs(), 60);
    }

    #[test]
    fn run_is_a_subcommand_not_a_default() {
        assert!(matches!(
            Cli::parse_from(["solstice", "run"]).command,
            Command::Run
        ));
    }
}
